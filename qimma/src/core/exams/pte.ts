/** Builds the weights table from each task type's `skills` plus an overall share. */
function weightsFor(overall: Partial<Record<TaskTypeId, number>>) {
  const out: ExamSpec['weights'] = {};
  for (const [id, value] of Object.entries(overall) as [TaskTypeId, number][]) {
    out[id] = { overall: value, skills: TASK_TYPES[id].skills };
  }
  return out;
}

